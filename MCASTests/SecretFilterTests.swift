// SecretFilterTests.swift — passwords and secrets must never be saved.

import AppKit
import XCTest
@testable import MCAS

final class SecretFilterTests: XCTestCase {
    func testNormalTextIsAllowed() {
        XCTAssertNil(SecretFilter.reasonToSkip(types: [.string], sourceBundleID: "com.apple.TextEdit"))
    }

    func testConcealedMarkerIsSkipped() {
        let types: [NSPasteboard.PasteboardType] = [.string, .init("org.nspasteboard.ConcealedType")]
        XCTAssertEqual(
            SecretFilter.reasonToSkip(types: types, sourceBundleID: "com.apple.Safari"),
            .markerType("org.nspasteboard.ConcealedType")
        )
    }

    func testTransientAndAutoGeneratedMarkersAreSkipped() {
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            XCTAssertNotNil(SecretFilter.reasonToSkip(types: [.string, .init(marker)], sourceBundleID: nil), marker)
        }
    }

    func testPasswordManagerAppIsSkipped() {
        XCTAssertEqual(
            SecretFilter.reasonToSkip(types: [.string], sourceBundleID: "com.bitwarden.desktop"),
            .ignoredApp("com.bitwarden.desktop")
        )
    }

    func testCustomIgnoreList() {
        XCTAssertNotNil(SecretFilter.reasonToSkip(types: [.string], sourceBundleID: "com.example.app", ignoredBundleIDs: ["com.example.app"]))
        XCTAssertNil(SecretFilter.reasonToSkip(types: [.string], sourceBundleID: "com.bitwarden.desktop", ignoredBundleIDs: []))
    }
}
