// SecretFilter.swift
//
// What: decides whether a copy must NOT be saved (passwords and other secrets).
// Why:  goal #4 of the PRD — never store passwords.
//
// How password managers signal "don't save this": they add special marker types
// to the clipboard (a community convention, see nspasteboard.org). We also skip
// anything copied while a password manager is the front app.
//
// v1.0 will add pattern checks (API keys, card numbers, OTP codes) here.

import AppKit

enum SecretFilter {
    enum SkipReason: Equatable, CustomStringConvertible {
        case markerType(String)
        case ignoredApp(String)

        var description: String {
            switch self {
            case .markerType(let type): return "marker type \(type)"
            case .ignoredApp(let bundleID): return "ignored app \(bundleID)"
            }
        }
    }

    /// Marker types meaning "this is a secret / temporary, don't keep it".
    static let markerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",       // passwords (1Password, Bitwarden, Keychain…)
        "org.nspasteboard.TransientType",       // temporary data
        "org.nspasteboard.AutoGeneratedType",   // generated by an app, not copied by you
        "com.agilebits.onepassword",            // older 1Password versions
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Apps whose copies we never save. Will be editable in Settings (v1.0).
    static let defaultIgnoredBundleIDs: Set<String> = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal",
        "org.keepassxc.keepassxc",
        "com.kee.keeweb",
        "com.enpass.Enpass-Desktop",
        "com.proton.pass.electron",
    ]

    /// Returns why a copy should be skipped, or nil if it's fine to save.
    static func reasonToSkip(
        types: [NSPasteboard.PasteboardType],
        sourceBundleID: String?,
        ignoredBundleIDs: Set<String> = defaultIgnoredBundleIDs
    ) -> SkipReason? {
        if let marker = types.first(where: { markerTypes.contains($0.rawValue) }) {
            return .markerType(marker.rawValue)
        }
        if let bundleID = sourceBundleID, ignoredBundleIDs.contains(bundleID) {
            return .ignoredApp(bundleID)
        }
        return nil
    }
}
